def get_currency_for_location(location: str) -> str:
    if not location:
        return "USD"
    loc_lower = location.lower().strip()
    
    # Check static map
    for key, code in CURRENCY_MAP.items():
        if key in loc_lower:
            return code
            
    # Fallback to LLM
    try:
        res = _llm_text(
            "You are a currency resolver. Based on the given city or country, respond with ONLY its standard ISO 4217 three-letter currency code (e.g. USD, EUR, GBP, JPY, INR). Do not include any formatting, punctuation, or other text.",
            f"Location: {location}"
        )
        code = res.strip().upper()
        if len(code) == 3 and code.isalpha():
            return code
    except Exception:
        pass
        
    return "USD"


def get_exchange_rate(from_currency: str, to_currency: str) -> float:
    import urllib.request
    
    api_key = os.getenv("EXCHANGE_RATE_API_KEY")
    if not api_key:
        print("⚠️ Warning: EXCHANGE_RATE_API_KEY is not set in the environment.")
        return 1.0
        
    if from_currency.upper() == to_currency.upper():
        return 1.0
        
    url = f"https://v6.exchangerate-api.com/v6/{api_key}/latest/{to_currency.upper()}"
    try:
        req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
        with urllib.request.urlopen(req, timeout=5) as response:
            data = json.loads(response.read().decode())
            if data.get("result") == "success":
                rates = data.get("conversion_rates", {})
                rate = rates.get(from_currency.upper())
                if rate is not None:
                    print(f"📊 Live exchange rate: 1 {to_currency.upper()} = {rate} {from_currency.upper()}")
                    return float(rate)
    except Exception as e:
        print(f"⚠️ Error fetching exchange rate from API: {e}")
        
    return 1.0


def _get_user_query(state: TravelState) -> str:
    user_query = state.get("user_query", "")

    if user_query:
        return user_query

    for message in reversed(state.get("messages", [])):
        if isinstance(message, HumanMessage):
            content = message.content
            if isinstance(content, str):
                return content

        if hasattr(message, "type") and message.type == "human":
            content = getattr(message, "content", "")
            if isinstance(content, str):
                return content

        if isinstance(message, dict) and message.get("type") == "human":
            content = message.get("content", "")
            if isinstance(content, str):
                return content

    return ""


def supervisor_node(state: TravelState) -> dict[str, Any]:
    user_query = _get_user_query(state)

    guardrail_system = (
        "You are a strict travel safety guardrail. Your task is to determine whether "
        "the user query is strictly travel-related, such as planning a trip, booking flights/hotels, "
        "checking weather, estimating budgets, or listing travel itineraries/activities.\n"
        "Crucially, you must BLOCK:\n"
        "- General tutorials or 'how-to' guides (e.g., learning how to ride a bike, swim, code, cook, or speak a language), "
        "even if the user claims it is 'during the trip' or 'for travel'.\n"
        "- General knowledge, jokes, programming, math, essays, or off-topic conversational fillers.\n"
        "If the query is strictly travel-related, respond with {\"allowed\": true, \"reason\": \"Explanation\"}.\n"
        "If it is not, respond with {\"allowed\": false, \"reason\": \"Explanation why it is blocked\"}.\n"
        "Respond ONLY with valid JSON in this format: "
        '{"allowed": true, "reason": "..."}'
    )

    guardrail_result = _llm_text(
        guardrail_system,
        f"Query: {user_query}",
    )
    guardrail_json = _json_from_llm(guardrail_result)

    allowed = bool(guardrail_json.get("allowed", False))
    reason = guardrail_json.get(
        "reason",
        "Query is not travel-related.",
    )

    if not allowed:
        return {
            "user_query": user_query,
            "guardrail_allowed": False,
            "guardrail_reason": reason,
            "final_response": reason,
            "llm_calls": state.get("llm_calls", 0) + 1,
        }

    supervisor_system = (
        "You are a travel coordinator supervisor. Analyze the user's travel request.\n"
        "First, classify the user's intent as either:\n"
        "- \"trip_planning\": if they request a multi-day itinerary or trip plan.\n"
        "- \"direct_query\": if they only ask a single-topic question, e.g., checking weather at a destination, searching flight options between airports, or listing hotel options, and do NOT request a multi-day itinerary.\n\n"
        "Select only the specialist agents actually required. Available specialists are:\n"
        "- flight_agent: routes, ticket information, schedules\n"
        "- hotel_agent: accommodation and locations\n"
        "- weather_agent: destination weather conditions\n"
        "- budget_agent: total trip cost estimation\n\n"
        "Extract these trip constraints: destination, origin, duration, budget, travel_style.\n"
        "Respond ONLY with valid JSON in exactly this structure:\n"
        '{"intent_mode": "trip_planning", '
        '"selected_agents": ["flight_agent"], '
        '"trip_constraints": {"destination": "...", "origin": "...", '
        '"duration": "...", "budget": "...", "travel_style": "..."}, '
        '"reasoning": "..."}'
    )

    supervisor_result = _llm_text(
        supervisor_system,
        f"Query: {user_query}",
    )
    supervisor_json = _json_from_llm(supervisor_result)

    selected_agents = [
        agent
        for agent in supervisor_json.get("selected_agents", [])
        if agent in SPECIALIST_NAMES
    ]

    intent_mode = supervisor_json.get("intent_mode", "trip_planning")
    if intent_mode not in ("trip_planning", "direct_query"):
        intent_mode = "trip_planning"

    constraints = supervisor_json.get("trip_constraints")
    if not isinstance(constraints, dict):
        constraints = _empty_constraints()

    normalized_constraints = _empty_constraints()
    normalized_constraints.update(constraints)

    origin_currency = get_currency_for_location(normalized_constraints.get("origin", ""))
    destination_currency = get_currency_for_location(normalized_constraints.get("destination", ""))
    exchange_rate = get_exchange_rate(origin_currency, destination_currency)

    return {
        "user_query": user_query,
        "guardrail_allowed": True,
        "guardrail_reason": "",
        "selected_agents": selected_agents,
        "trip_constraints": normalized_constraints,
        "supervisor_reasoning": supervisor_json.get("reasoning", ""),
        "intent_mode": intent_mode,
        "origin_currency": origin_currency,
        "destination_currency": destination_currency,
        "exchange_rate": exchange_rate,
        "llm_calls": state.get("llm_calls", 0) + 2,
    }


