class TravelState(TypedDict, total=False):
    messages: Annotated[list[AnyMessage], operator.add]
    user_query: str
    guardrail_allowed: bool
    guardrail_reason: str
    selected_agents: list[str]
    trip_constraints: dict[str, Any]
    supervisor_reasoning: str
    flight_results: str
    hotel_results: str
    weather_results: str
    budget_results: str
    itinerary: str
    approval_request: str
    approved: Optional[bool]
    human_feedback: Optional[str]
    final_response: str
    llm_calls: int


SPECIALIST_NAMES = {
    "flight_agent",
    "hotel_agent",
    "weather_agent",
    "budget_agent",
}


def get_llm() -> ChatGroq:
    api_key = os.getenv("GROQ_API_KEY")
    if not api_key:
        raise ValueError("GROQ_API_KEY is not set in .env")

    model_name = os.getenv("GROQ_MODEL", "groq/compound")

    return ChatGroq(
        model=model_name,
        groq_api_key=api_key,
        temperature=0.0,
    )


def _llm_text(system_prompt: str, user_prompt: str) -> str:
    import time
    llm = get_llm()
    messages = [
        SystemMessage(content=system_prompt),
        HumanMessage(content=user_prompt)
    ]
    max_retries = 4
    delay = 15  # start with 15 seconds to allow TPM decay
    
    for attempt in range(max_retries):
        try:
            res = llm.invoke(messages)
            return res.content
        except Exception as e:
            error_str = str(e).lower()
            # Catch rate limit, TPM/RPM limits, HTTP 429, or HTTP 413 token-limit errors
            if any(term in error_str for term in ("rate_limit", "tpm", "tokens per minute", "too large", "overloaded", "413", "429")):
                if attempt < max_retries - 1:
                    print(f"⚠️ Groq rate/TPM limit hit. Sleeping {delay}s before retry (Attempt {attempt+1}/{max_retries})...")
                    time.sleep(delay)
                    delay *= 2
                    continue
            raise e


def _json_from_llm(text: str) -> dict[str, Any]:
    # Strip <think>...</think> blocks if generated by reasoning models
    if "<think>" in text and "</think>" in text:
        parts = text.split("</think>", 1)
        text = parts[1]

    text = text.strip()
    if not text:
        return {}

    start = text.find("{")
    end = text.rfind("}")

    if start == -1 or end == -1 or end < start:
        return {}

    json_str = text[start : end + 1]

    try:
        return json.loads(json_str)
    except json.JSONDecodeError:
        return {}


def _empty_constraints() -> dict[str, Any]:
    return {
        "destination": "",
        "origin": "",
        "duration": "",
        "budget": "",
        "travel_style": "",
    }


def _get_user_query(state: TravelState) -> str:
    user_query = state.get("user_query", "")

    if user_query:
        return user_query

    for message in reversed(state.get("messages", [])):
        if isinstance(message, HumanMessage):
            content = message.content
            if isinstance(content, str):
                return content

        if hasattr(message, "type") and message.type == "human":
            content = getattr(message, "content", "")
            if isinstance(content, str):
                return content

        if isinstance(message, dict) and message.get("type") == "human":
            content = message.get("content", "")
            if isinstance(content, str):
                return content

    return ""


def supervisor_node(state: TravelState) -> dict[str, Any]:
    user_query = _get_user_query(state)

    guardrail_system = (
        "You are a strict travel safety guardrail. Your task is to determine whether "
        "the user query is travel-related, such as planning a trip, booking flights, "
        "finding hotels, checking weather, or estimating a travel budget. "
        "If the query is travel-related, you must respond with {\"allowed\": true, \"reason\": \"Explanation\"}.\n"
        "If the query is NOT travel-related (e.g. general questions, math, jokes, programming, etc.), you must respond with {\"allowed\": false, \"reason\": \"Explanation why it is blocked\"}.\n"
        "Respond ONLY with valid JSON in this format: "
        '{"allowed": true, "reason": "..."}'
    )

    guardrail_result = _llm_text(
        guardrail_system,
        f"Query: {user_query}",
    )
    guardrail_json = _json_from_llm(guardrail_result)

    allowed = bool(guardrail_json.get("allowed", False))
    reason = guardrail_json.get(
        "reason",
        "Query is not travel-related.",
    )

    if not allowed:
        return {
            "user_query": user_query,
            "guardrail_allowed": False,
            "guardrail_reason": reason,
            "final_response": reason,
            "llm_calls": state.get("llm_calls", 0) + 1,
        }

    supervisor_system = (
        "You are a travel coordinator supervisor. Analyze the user's travel request.\n"
        "Select only the specialist agents actually required. Available specialists are:\n"
        "- flight_agent: routes, ticket information, schedules\n"
        "- hotel_agent: accommodation and locations\n"
        "- weather_agent: destination weather conditions\n"
        "- budget_agent: total trip cost estimation\n\n"
        "Extract these trip constraints: destination, origin, duration, budget, travel_style.\n"
        "Respond ONLY with valid JSON in exactly this structure:\n"
        '{"selected_agents": ["flight_agent"], '
        '"trip_constraints": {"destination": "...", "origin": "...", '
        '"duration": "...", "budget": "...", "travel_style": "..."}, '
        '"reasoning": "..."}'
    )

    supervisor_result = _llm_text(
        supervisor_system,
        f"Query: {user_query}",
    )
    supervisor_json = _json_from_llm(supervisor_result)

    selected_agents = [
        agent
        for agent in supervisor_json.get("selected_agents", [])
        if agent in SPECIALIST_NAMES
    ]

    constraints = supervisor_json.get("trip_constraints")
    if not isinstance(constraints, dict):
        constraints = _empty_constraints()

    normalized_constraints = _empty_constraints()
    normalized_constraints.update(constraints)

    return {
        "user_query": user_query,
        "guardrail_allowed": True,
        "guardrail_reason": "",
        "selected_agents": selected_agents,
        "trip_constraints": normalized_constraints,
        "supervisor_reasoning": supervisor_json.get("reasoning", ""),
        "llm_calls": state.get("llm_calls", 0) + 2,
    }


def flight_node(state: TravelState) -> dict[str, Any]:
    constraints = state.get("trip_constraints", {})
    result = _llm_text(
        "You are a flight specialist agent. Suggest suitable flight options, "
        "airline carriers, routes, schedules, and approximate price ranges. "
        "Clearly state that prices and schedules are estimates unless real-time "
        "flight data is available. Return a clear Markdown summary.",
        f"Constraints: {json.dumps(constraints, ensure_ascii=False)}",
    )
    return {
        "flight_results": result,
        "llm_calls": state.get("llm_calls", 0) + 1,
    }


