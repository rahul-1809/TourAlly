def itinerary_node(state: TravelState) -> dict[str, Any]:
    user_query = state.get("user_query", "")
    constraints = state.get("trip_constraints", {})
    feedback = state.get("human_feedback", "")

    prompt_content = f"""
User Request:
{user_query}

Trip Constraints:
{json.dumps(constraints, ensure_ascii=False)}

Flight Options:
{state.get("flight_results", "Not requested")}

Hotel Options:
{state.get("hotel_results", "Not requested")}

Weather Details:
{state.get("weather_results", "Not requested")}

Budget Estimate:
{state.get("budget_results", "Not requested")}
"""

    if feedback:
        prompt_content += (
            f"\nPrevious human revision feedback:\n{feedback}\n"
            "Revise the itinerary using this feedback."
        )

    system_prompt = (
        "You are a master travel planner. Synthesize the provided information into "
        "a cohesive day-by-day itinerary. Use detailed Markdown, clean headings, "
        "bold text, bullet lists, and emojis. Do not claim that an external booking "
        "or weather API was checked unless the input explicitly contains such data.\n\n"
        "Separate the response using exactly these boundaries:\n"
        "--- ITINERARY_START ---\n"
        "[Detailed Markdown Itinerary]\n"
        "--- SUMMARY_START ---\n"
        "[Short Summary for Approval]"
    )

    result = _llm_text(system_prompt, prompt_content)

    itinerary = result.strip()
    summary = "Draft travel itinerary prepared for approval."

    if "--- SUMMARY_START ---" in result:
        itinerary_part, summary_part = result.split(
            "--- SUMMARY_START ---", 1
        )
        itinerary = itinerary_part.replace(
            "--- ITINERARY_START ---", ""
        ).strip()
        summary = summary_part.strip()
    elif "--- ITINERARY_START ---" in result:
        itinerary = result.replace(
            "--- ITINERARY_START ---", ""
        ).strip()

    return {
        "itinerary": itinerary,
        "approval_request": summary,
        "approved": None,
        "human_feedback": None,
        "llm_calls": state.get("llm_calls", 0) + 1,
    }


def hitl_node(state: TravelState) -> dict[str, Any]:
    if state.get("approved") is True:
        return {}

    resume_data = interrupt(
        {
            "summary": state.get(
                "approval_request",
                "Review the travel plan.",
            ),
            "itinerary": state.get("itinerary", ""),
            "user_query": state.get("user_query", ""),
            "trip_constraints": state.get("trip_constraints", {}),
        }
    )

    if not isinstance(resume_data, dict):
        resume_data = {}

    return {
        "approved": bool(resume_data.get("approved", False)),
        "human_feedback": str(resume_data.get("feedback", "")),
    }


def finalize_node(state: TravelState) -> dict[str, Any]:
    return {
        "final_response": state.get("itinerary", ""),
        "approved": True,
    }


def route_after_supervisor(state: TravelState) -> str:
    if not state.get("guardrail_allowed", True):
        return "end"

    agents = state.get("selected_agents", [])
    if not agents:
        return "itinerary_agent"

    # The specialist coordinator runs only the selected specialists and creates
    # a single synchronization point before itinerary generation.
    return "specialists"


def specialists_node(state: TravelState) -> dict[str, Any]:
    """Run the selected specialist agents sequentially as a single fanning-in point.

    This avoids triggering itinerary_node multiple times when the supervisor
    selects more than one specialist.
    """
    constraints = state.get("trip_constraints", {})
    selected = state.get("selected_agents", [])
    updates: dict[str, Any] = {}
    llm_calls = state.get("llm_calls", 0)

    # 1. Flight Agent
    if "flight_agent" in selected:
        origin = constraints.get("origin", "")
        destination = constraints.get("destination", "")
        flight_data = "No flights retrieved."
        
        if origin and destination:
            iata_codes = extract_iata_codes(origin, destination)
            origin_iata = iata_codes.get("origin_iata")
            dest_iata = iata_codes.get("destination_iata")
            if origin_iata and dest_iata:
                try:
                    flight_data = asyncio.run(aviation_get_flights(origin_iata, dest_iata))
                except Exception as e:
                    flight_data = f"Error fetching flight data: {e}"
        
        system_prompt = (
            "You are a flight specialist agent. Based on these constraints: {constraints} and the real-time flight details: {flight_data}, suggest suitable flight options, airline carriers, routes, and price ranges. Return the response as a clear markdown summary."
        )
        system_prompt = system_prompt.replace("{constraints}", json.dumps(constraints, ensure_ascii=False)).replace("{flight_data}", flight_data)
        
        result = _llm_text(
            system_prompt,
            f"Constraints: {json.dumps(constraints, ensure_ascii=False)}"
        )
        updates["flight_results"] = result
        llm_calls += 2

    # 2. Hotel Agent
    if "hotel_agent" in selected:
        destination = constraints.get("destination", "")
        hotel_data = "No hotel search data retrieved."
        if destination:
            try:
                hotel_data = asyncio.run(tavily_mcp_search(f"best hotels and neighborhoods in {destination}"))
            except Exception as e:
                hotel_data = f"Error fetching hotel data: {e}"
                
        system_prompt = (
            "You are a hotel specialist agent. Based on these constraints: {constraints} and the Tavily search results: {hotel_data}, suggest suitable accommodation options, neighborhoods, and hotel recommendations. Return the response as a clear markdown summary."
        )
        system_prompt = system_prompt.replace("{constraints}", json.dumps(constraints, ensure_ascii=False)).replace("{hotel_data}", hotel_data)
        
        result = _llm_text(
            system_prompt,
            f"Constraints: {json.dumps(constraints, ensure_ascii=False)}"
        )
        updates["hotel_results"] = result
        llm_calls += 1

    # 3. Weather Agent
    if "weather_agent" in selected:
        destination = constraints.get("destination", "")
        weather_data = "No weather forecast retrieved."
        if destination:
            try:
                weather_data = asyncio.run(forecast_mcp_search(destination, days=3))
            except Exception as e:
                weather_data = f"Error fetching weather forecast: {e}"
                
        system_prompt = (
            "You are a weather specialist agent. Based on these constraints: {constraints} and the weather forecast: {weather_data}, provide useful expected weather information for the destination. Return the response as a clear markdown summary."
        )
        system_prompt = system_prompt.replace("{constraints}", json.dumps(constraints, ensure_ascii=False)).replace("{weather_data}", weather_data)
        
        result = _llm_text(
            system_prompt,
            f"Constraints: {json.dumps(constraints, ensure_ascii=False)}"
        )
        updates["weather_results"] = result
        llm_calls += 1

    # 4. Budget Agent
    if "budget_agent" in selected:
        destination = constraints.get("destination", "")
        budget_data = "No budget search data retrieved."
        if destination:
            try:
                budget_data = asyncio.run(tavily_mcp_search(f"typical daily budget activities and local transport costs in {destination}"))
            except Exception as e:
                budget_data = f"Error fetching budget data: {e}"
                
        system_prompt = (
            "You are a travel budget specialist. Based on these constraints: {constraints} and the typical costs context: {budget_data}, estimate the total trip cost. Include transportation, accommodation, activities, local transport, and contingency. Return a clear markdown summary."
        )
        system_prompt = system_prompt.replace("{constraints}", json.dumps(constraints, ensure_ascii=False)).replace("{budget_data}", budget_data)
        
        result = _llm_text(
            system_prompt,
            f"Constraints: {json.dumps(constraints, ensure_ascii=False)}"
        )
        updates["budget_results"] = result
        llm_calls += 1

    updates["llm_calls"] = llm_calls
    return updates


def route_after_hitl(state: TravelState) -> str:
    if state.get("approved") is True:
        return "finalize"
    return "itinerary_agent"


workflow = StateGraph(TravelState)

workflow.add_node("supervisor_agent", supervisor_node)
workflow.add_node("specialists", specialists_node)
workflow.add_node("itinerary_agent", itinerary_node)
workflow.add_node("hitl_approval", hitl_node)
workflow.add_node("finalize", finalize_node)

workflow.add_edge(START, "supervisor_agent")

workflow.add_conditional_edges(
    "supervisor_agent",
    route_after_supervisor,
    {
        "specialists": "specialists",
        "itinerary_agent": "itinerary_agent",
        "end": END,
    },
)

workflow.add_edge("specialists", "itinerary_agent")
workflow.add_edge("itinerary_agent", "hitl_approval")

workflow.add_conditional_edges(
    "hitl_approval",
    route_after_hitl,
    {
        "finalize": "finalize",
        "itinerary_agent": "itinerary_agent",
    },
)

workflow.add_edge("finalize", END)


@contextlib.contextmanager
def get_graph():
    database_url = os.getenv("DATABASE_URL")

    if database_url:
        with PostgresSaver.from_conn_string(database_url) as saver:
            saver.setup()
            yield workflow.compile(checkpointer=saver)
    else:
        saver = MemorySaver()
        yield workflow.compile(checkpointer=saver)


def run_travel_agent(
    message: str,
    thread_id: Optional[str] = None,
) -> dict[str, Any]:
    if not thread_id:
        thread_id = str(uuid.uuid4())

    config = {"configurable": {"thread_id": thread_id}}

    with get_graph() as graph:
        graph.invoke(
            {
                "user_query": message,
                "messages": [HumanMessage(content=message)],
                "llm_calls": 0,
            },
            config,
        )

        state = graph.get_state(config)

        if state.values.get("guardrail_allowed") is False:
            return {
                "thread_id": thread_id,
                "status": "blocked",
                "content": state.values.get(
                    "final_response",
                    "Query blocked by guardrail.",
                ),
                "awaiting_approval": False,
                "agents_run": ["supervisor_agent"],
            }

        is_awaiting = bool(
            state.next and "hitl_approval" in state.next
        )

        if is_awaiting:
            return {
                "thread_id": thread_id,
                "status": "awaiting_approval",
                "content": state.values.get(
                    "approval_request",
                    "Review travel plan",
                ),
                "itinerary": state.values.get("itinerary", ""),
                "awaiting_approval": True,
                "agents_run": (
                    ["supervisor_agent"]
                    + state.values.get("selected_agents", [])
                    + ["itinerary_agent"]
                ),
            }

        return {
            "thread_id": thread_id,
            "status": "completed",
            "content": state.values.get("final_response", ""),
            "awaiting_approval": False,
            "agents_run": (
                ["supervisor_agent"]
                + state.values.get("selected_agents", [])
                + ["itinerary_agent", "finalize"]
            ),
        }


def resume_travel_agent(
    thread_id: str,
    approved: bool,
    feedback: str = "",
) -> dict[str, Any]:
    config = {"configurable": {"thread_id": thread_id}}

    with get_graph() as graph:
        graph.invoke(
            Command(
                resume={
                    "approved": approved,
                    "feedback": feedback,
                }
            ),
            config,
        )

        state = graph.get_state(config)

        is_awaiting = bool(
            state.next and "hitl_approval" in state.next
        )

        if is_awaiting:
            return {
                "thread_id": thread_id,
                "status": "awaiting_approval",
                "content": state.values.get(
                    "approval_request",
                    "Review travel plan",
                ),
                "itinerary": state.values.get("itinerary", ""),
                "awaiting_approval": True,
                "agents_run": ["itinerary_agent"],
            }

        return {
            "thread_id": thread_id,
            "status": "completed",
            "content": state.values.get("final_response", ""),
            "awaiting_approval": False,
            "agents_run": ["finalize"],
        }
