def itinerary_node(state: TravelState) -> dict[str, Any]:
    user_query = state.get("user_query", "")
    constraints = state.get("trip_constraints", {})
    feedback = state.get("human_feedback", "")
    origin_currency = state.get("origin_currency", "USD")
    destination_currency = state.get("destination_currency", "USD")
    exchange_rate = state.get("exchange_rate", 1.0)

    prompt_content = f"""
User Request:
{user_query}

Trip Constraints:
{json.dumps(constraints, ensure_ascii=False)}

Flight Options:
{state.get("flight_results", "Not requested")}

Hotel Options:
{state.get("hotel_results", "Not requested")}

Weather Details:
{state.get("weather_results", "Not requested")}

Budget Estimate:
{state.get("budget_results", "Not requested")}
"""

    print(f"📝 [Itinerary Agent] Synthesizing day-by-day plan. Human feedback received: '{feedback}'")

    if feedback:
        prompt_content += (
            f"\n⚠️ CRITICAL REVISION REQUEST FROM HUMAN ADVISOR:\n"
            f"Please revise the previous draft itinerary strictly incorporating the following feedback:\n"
            f"\"{feedback}\"\n\n"
            f"You MUST adjust the hotels, flights, budget, schedules, or other elements of the travel plan "
            f"to satisfy this request."
        )

    system_prompt = (
        "You are a master travel planner. Synthesize the provided information into "
        "a cohesive day-by-day itinerary. Use detailed Markdown, clean headings, "
        "bold text, bullet lists, and emojis. Do not claim that an external booking "
        "or weather API was checked unless the input explicitly contains such data.\n"
        "CRITICAL INSTRUCTION: The traveler's origin currency is '{origin_currency}' and the destination currency is '{destination_currency}'. "
        "You MUST display all monetary values, price ranges, daily costs, and the final budget breakdown table STRICTLY in the traveler's home currency '{origin_currency}' (using standard symbols like $, £, €, ₹). "
        "Do NOT use the destination currency '{destination_currency}' for any prices. "
        "The conversion rate is: 1 {destination_currency} = {exchange_rate} {origin_currency}.\n\n"
        "Separate the response using exactly these boundaries:\n"
        "--- ITINERARY_START ---\n"
        "[Detailed Markdown Itinerary]\n"
        "--- SUMMARY_START ---\n"
        "[Short Summary for Approval]"
    )
    system_prompt = (
        system_prompt
        .replace("{origin_currency}", origin_currency)
        .replace("{destination_currency}", destination_currency)
        .replace("{exchange_rate}", str(exchange_rate))
    )

    result = _llm_text(system_prompt, prompt_content)

    itinerary = result.strip()
    summary = "Draft travel itinerary prepared for approval."

    if "--- SUMMARY_START ---" in result:
        itinerary_part, summary_part = result.split(
            "--- SUMMARY_START ---", 1
        )
        itinerary = itinerary_part.replace(
            "--- ITINERARY_START ---", ""
        ).strip()
        summary = summary_part.strip()
    elif "--- ITINERARY_START ---" in result:
        itinerary = result.replace(
            "--- ITINERARY_START ---", ""
        ).strip()

    return {
        "itinerary": itinerary,
        "approval_request": summary,
        "approved": None,
        "human_feedback": None,
        "llm_calls": state.get("llm_calls", 0) + 1,
    }


def hitl_node(state: TravelState) -> dict[str, Any]:
    if state.get("approved") is True:
        return {}

    resume_data = interrupt(
        {
            "summary": state.get(
                "approval_request",
                "Review the travel plan.",
            ),
            "itinerary": state.get("itinerary", ""),
            "user_query": state.get("user_query", ""),
            "trip_constraints": state.get("trip_constraints", {}),
        }
    )

    if not isinstance(resume_data, dict):
        resume_data = {}

    return {
        "approved": bool(resume_data.get("approved", False)),
        "human_feedback": str(resume_data.get("feedback", "")),
    }


def finalize_node(state: TravelState) -> dict[str, Any]:
    return {
        "final_response": state.get("itinerary", ""),
        "approved": True,
    }


def route_after_supervisor(state: TravelState) -> str:
    if not state.get("guardrail_allowed", True):
        return "end"

    agents = state.get("selected_agents", [])
    if not agents:
        return "itinerary_agent"

    # The specialist coordinator runs only the selected specialists and creates
    # a single synchronization point before itinerary generation.
    return "specialists"


def specialists_node(state: TravelState) -> dict[str, Any]:
    """Run the selected specialist agents sequentially as a single fanning-in point.

    This avoids triggering itinerary_node multiple times when the supervisor
    selects more than one specialist.
    """
    constraints = state.get("trip_constraints", {})
    selected = state.get("selected_agents", [])
    updates: dict[str, Any] = {}
    llm_calls = state.get("llm_calls", 0)

    # 1. Flight Agent
    if "flight_agent" in selected:
        origin = constraints.get("origin", "")
        destination = constraints.get("destination", "")
        flight_data = "No flights retrieved."
        
        if origin and destination:
            iata_codes = extract_iata_codes(origin, destination)
            origin_iata = iata_codes.get("origin_iata")
            dest_iata = iata_codes.get("destination_iata")
            if origin_iata and dest_iata:
                try:
                    flight_data = asyncio.run(aviation_get_flights(origin_iata, dest_iata))
                except Exception as e:
                    flight_data = f"Error fetching flight data: {e}"
        
        system_prompt = (
            "You are a flight specialist agent. Based on these constraints: {constraints} and the real-time flight details: {flight_data}, suggest suitable flight options, airline carriers, routes, and price ranges. Keep your response extremely concise (max 200 words) and output a clear markdown summary."
        )
        system_prompt = system_prompt.replace("{constraints}", json.dumps(constraints, ensure_ascii=False)).replace("{flight_data}", flight_data)
        
        result = _llm_text(
            system_prompt,
            f"Constraints: {json.dumps(constraints, ensure_ascii=False)}"
        )
        updates["flight_results"] = result
        llm_calls += 2

    # 2. Hotel Agent
    if "hotel_agent" in selected:
        destination = constraints.get("destination", "")
        hotel_data = "No hotel search data retrieved."
        if destination:
            try:
                hotel_data = asyncio.run(tavily_mcp_search(f"best hotels and neighborhoods in {destination}"))
            except Exception as e:
                hotel_data = f"Error fetching hotel data: {e}"
                
        system_prompt = (
            "You are a hotel specialist agent. Based on these constraints: {constraints} and the Tavily search results: {hotel_data}, suggest suitable accommodation options, neighborhoods, and hotel recommendations. Keep your response extremely concise (max 200 words) and output a clear markdown summary."
        )
        system_prompt = system_prompt.replace("{constraints}", json.dumps(constraints, ensure_ascii=False)).replace("{hotel_data}", hotel_data)
        
        result = _llm_text(
            system_prompt,
            f"Constraints: {json.dumps(constraints, ensure_ascii=False)}"
        )
        updates["hotel_results"] = result
        llm_calls += 1

    # 3. Weather Agent
    if "weather_agent" in selected:
        destination = constraints.get("destination", "")
        weather_data = "No weather forecast retrieved."
        if destination:
            try:
                weather_data = asyncio.run(forecast_mcp_search(destination, days=3))
            except Exception as e:
                weather_data = f"Error fetching weather forecast: {e}"
                
        system_prompt = (
            "You are a weather specialist agent. Based on these constraints: {constraints} and the weather forecast: {weather_data}, provide useful expected weather information for the destination. Keep your response extremely concise (max 150 words) and output a clear markdown summary."
        )
        system_prompt = system_prompt.replace("{constraints}", json.dumps(constraints, ensure_ascii=False)).replace("{weather_data}", weather_data)
        
        result = _llm_text(
            system_prompt,
            f"Constraints: {json.dumps(constraints, ensure_ascii=False)}"
        )
        updates["weather_results"] = result
        llm_calls += 1

    # 4. Budget Agent
    if "budget_agent" in selected:
        destination = constraints.get("destination", "")
        budget_data = "No budget search data retrieved."
        if destination:
            try:
                budget_data = asyncio.run(tavily_mcp_search(f"typical daily budget activities and local transport costs in {destination}"))
            except Exception as e:
                budget_data = f"Error fetching budget data: {e}"
                
        origin_currency = state.get("origin_currency", "USD")
        destination_currency = state.get("destination_currency", "USD")
        exchange_rate = state.get("exchange_rate", 1.0)
        
        system_prompt = (
            "You are a travel budget specialist. Based on these constraints: {constraints} and the typical costs context: {budget_data}, estimate the total trip cost. Include transportation, accommodation, activities, local transport, and contingency.\n"
            "CRITICAL INSTRUCTION: The traveler's origin is '{origin}' (Currency: {origin_currency}) and the destination is '{destination}' (Currency: {destination_currency}). "
            "You MUST present the entire budget estimation, daily breakdown, and item costs STRICTLY in the traveler's home currency '{origin_currency}' (symbol/format). "
            "Use the conversion rate: 1 {destination_currency} = {exchange_rate} {origin_currency} to convert any local destination prices into {origin_currency} before summarizing them.\n"
            "Keep your response extremely concise (max 180 words) and output a clear markdown summary."
        )
        system_prompt = (
            system_prompt
            .replace("{constraints}", json.dumps(constraints, ensure_ascii=False))
            .replace("{budget_data}", budget_data)
            .replace("{origin}", constraints.get("origin", ""))
            .replace("{destination}", constraints.get("destination", ""))
            .replace("{origin_currency}", origin_currency)
            .replace("{destination_currency}", destination_currency)
            .replace("{exchange_rate}", str(exchange_rate))
        )
        
        result = _llm_text(
            system_prompt,
            f"Constraints: {json.dumps(constraints, ensure_ascii=False)}"
        )
        updates["budget_results"] = result
        llm_calls += 1

    updates["llm_calls"] = llm_calls
    return updates


def direct_response_node(state: TravelState) -> dict[str, Any]:
    selected = state.get("selected_agents", [])
    results = []

    # Map selected agents to their respective results fields
    if "flight_agent" in selected and state.get("flight_results"):
        results.append(f"### ✈️ Flight Recommendations\n{state['flight_results']}")
    if "hotel_agent" in selected and state.get("hotel_results"):
        results.append(f"### 🏨 Accommodation Options\n{state['hotel_results']}")
    if "weather_agent" in selected and state.get("weather_results"):
        results.append(f"### 🌤️ Weather Forecast\n{state['weather_results']}")
    if "budget_agent" in selected and state.get("budget_results"):
        results.append(f"### 💰 Budget & Cost Analysis\n{state['budget_results']}")

    if results:
        final_text = "\n\n---\n\n".join(results)
    else:
        final_text = "No results compiled for your direct query."

    return {
        "final_response": final_text,
        "approved": True
    }


def route_after_specialists(state: TravelState) -> str:
    if state.get("intent_mode") == "direct_query":
        return "direct_response"
    return "itinerary_agent"


def route_after_hitl(state: TravelState) -> str:
    if state.get("approved") is True:
        return "finalize"
    return "itinerary_agent"


